import { expect, test } from '@playwright/test'
import { mockAdminAuth, signInAdmin } from './admin-auth-fixture'
import { mockCinemaAdmin } from './admin-cinema-fixture'

test('cinema and room edits persist through authenticated APIs; empty layouts can be created', async ({ page }) => {
  await mockAdminAuth(page)
  const backend = await mockCinemaAdmin(page)
  await page.goto('/admin/cinemas')
  await signInAdmin(page)
  await page.getByRole('button', { name: 'Chỉnh sửa Rạp thử nghiệm', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Tên rạp').fill('Rạp đã cập nhật')
  await dialog.getByRole('button', { name: 'Lưu thay đổi' }).click()
  await expect(dialog).not.toBeVisible()
  expect(backend.writes[0]).toMatchObject({ path: `/admin/cinemas/${backend.cinemas[0].id}`, method: 'PUT', body: { name: 'Rạp đã cập nhật', timezone: 'Asia/Ho_Chi_Minh' } })
  await page.getByRole('button', { name: 'Quản lý phòng Rạp đã cập nhật', exact: true }).click()
  await page.getByLabel('Tên phòng mới').fill('Phòng mới')
  await page.getByRole('button', { name: 'Thêm phòng', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Phòng mới', exact: true })).toBeVisible()
  expect(backend.writes[1]).toMatchObject({ method: 'POST', body: { name: 'Phòng mới' } })
  await page.getByRole('button', { name: 'Đổi tên Phòng mới', exact: true }).click()
  await page.getByLabel('Đổi tên phòng', { exact: true }).fill('Phòng 02')
  await page.getByRole('button', { name: 'Lưu tên phòng', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Phòng 02', exact: true })).toBeVisible()
  expect(backend.writes[2]).toMatchObject({ path: '/admin/auditoriums/room-1', method: 'PUT', body: { name: 'Phòng 02' } })
  await page.getByRole('button', { name: 'Chỉnh sơ đồ ghế Phòng 02', exact: true }).click()
  await expect(page.getByText('Chưa có sơ đồ ghế.', { exact: true })).toBeVisible()
  await page.getByLabel('Số hàng', { exact: true }).fill('1')
  await page.getByLabel('Ghế mỗi hàng', { exact: true }).fill('2')
  await page.getByRole('button', { name: 'Tạo sơ đồ', exact: true }).click()
  await page.getByRole('button', { name: 'Chọn cả hàng A' }).click()
  await page.getByRole('button', { name: 'Ghép ghế đôi' }).click()
  await page.getByRole('button', { name: 'Lưu sơ đồ', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Quản lý phòng · Rạp đã cập nhật' })).toBeVisible()
  const seats = backend.seats.filter(s => s.auditoriumId === 'room-1')
  expect(seats).toHaveLength(2)
  expect(seats[0].seatType).toBe('COUPLE')
  expect(seats[0].pairedSeatId).toBe(seats[1].id)
  expect(seats[1].pairedSeatId).toBe(seats[0].id)
  expect(await page.evaluate(() => localStorage.getItem('cinemat.admin-demo.v1'))).toBeNull()
})

test('draft showtimes survive reload and can be edited, published and cancelled', async ({ page }) => {
  await mockAdminAuth(page)
  const backend = await mockCinemaAdmin(page)
  await page.addInitScript(() => localStorage.setItem('cinemat.admin-demo.v1', '{broken'))
  await page.goto('/admin/showtimes')
  await signInAdmin(page)
  await page.getByRole('button', { name: 'Thêm suất chiếu', exact: true }).click()
  let dialog = page.getByRole('dialog')
  await dialog.getByLabel('Bắt đầu', { exact: true }).fill('2027-01-02T18:00')
  await dialog.getByLabel('Kết thúc', { exact: true }).fill('2027-01-02T20:00')
  await dialog.getByRole('button', { name: 'Lưu suất nháp' }).click()
  await expect(dialog).not.toBeVisible()
  expect(backend.writes[0]).toMatchObject({ path: '/showtimes', method: 'POST', body: { currency: 'VND', priceMinor: 95000 } })
  expect(backend.writes[0].body.startsAt).toBe(backend.writes[0].body.salesCloseAt)
  await expect(page.getByRole('cell', { name: 'Bản nháp', exact: true })).toBeVisible()
  await page.reload()
  await signInAdmin(page)
  await page.getByRole('button', { name: 'Chỉnh sửa suất slot-0' }).click()
  dialog = page.getByRole('dialog')
  await expect(dialog.getByLabel('Phòng chiếu')).toBeDisabled()
  await dialog.getByLabel('Giá vé (VND)').fill('120000')
  await dialog.getByRole('button', { name: 'Lưu suất nháp' }).click()
  await expect(dialog).not.toBeVisible()
  expect(backend.writes[1]).toMatchObject({ path: '/admin/showtimes/slot-0', method: 'PUT', body: { priceMinor: 120000 } })
  await page.getByRole('button', { name: 'Phát hành', exact: true }).click()
  await expect(page.getByRole('cell', { name: 'Đã công bố', exact: true })).toBeVisible()
  expect(backend.writes[2].path).toBe('/showtimes/slot-0/publish')
  await expect(page.getByRole('button', { name: 'Chỉnh sửa suất slot-0' })).toHaveCount(0)
  await page.getByRole('combobox', { name: 'Lý do hủy slot-0' }).selectOption('TECHNICAL_ISSUE')
  await expect(page.getByRole('cell', { name: 'Đã hủy', exact: true })).toBeVisible()
  expect(backend.writes[3]).toMatchObject({ path: '/showtimes/slot-0/cancel', method: 'POST', body: { reasonCode: 'TECHNICAL_ISSUE' } })
  await page.getByRole('navigation', { name: 'Điều hướng quản trị' }).getByRole('link', { name: 'Phát hành suất', exact: true }).click()
  await expect(page.getByRole('cell', { name: 'Đã hủy', exact: true })).toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem('cinemat.admin-demo.v1'))).toBe('{broken')
})

test('API errors show retry without falling back to browser fixtures', async ({ page }) => {
  await mockAdminAuth(page)
  await mockCinemaAdmin(page)
  let failing = true
  await page.route('**/api/v1/admin/cinemas', route => failing
    ? route.fulfill({ status: 503, json: { code: 'DEPENDENCY_UNAVAILABLE', message: 'Dịch vụ đang bảo trì', traceId: 'trace-cinema-test' } })
    : route.fallback())
  await page.addInitScript(() => localStorage.setItem('cinemat.admin-demo.v1', '{broken'))
  await page.goto('/admin/cinemas')
  await signInAdmin(page)
  await expect(page.getByRole('alert')).toContainText('trace-cinema-test')
  await expect(page.getByRole('heading', { name: 'Rạp thử nghiệm' })).toHaveCount(0)
  failing = false
  await page.getByRole('button', { name: 'Thử lại', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Rạp thử nghiệm' })).toBeVisible()
  await page.getByRole('button', { name: 'Quản lý phòng Rạp thử nghiệm', exact: true }).click()
  await page.route('**/api/v1/admin/auditoriums/*/seats', route => route.fulfill({ status: 403, json: { code: 'FORBIDDEN', traceId: 'trace-seats' } }))
  await page.getByRole('button', { name: 'Chỉnh sơ đồ ghế Phòng thử nghiệm', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('không có quyền')
  await expect(page.getByRole('button', { name: 'Lưu sơ đồ', exact: true })).toHaveCount(0)
})

test('a concurrent layout lock is reported without discarding unsaved changes', async ({ page }) => {
  await mockAdminAuth(page)
  const backend = await mockCinemaAdmin(page)
  await page.route('**/api/v1/admin/auditoriums/*/seats', route => route.request().method() === 'PUT'
    ? route.fulfill({ status: 409, json: { code: 'LAYOUT_LOCKED', message: 'Layout locked', traceId: 'layout-race' } })
    : route.fallback())
  await page.goto('/admin/cinemas')
  await signInAdmin(page)
  await page.getByRole('button', { name: 'Quản lý phòng Rạp thử nghiệm', exact: true }).click()
  await page.getByRole('button', { name: 'Chỉnh sơ đồ ghế Phòng thử nghiệm', exact: true }).click()
  await page.getByRole('button', { name: 'Chọn cả hàng B' }).click()
  await page.getByRole('button', { name: 'Đổi sang VIP' }).click()
  await page.getByRole('button', { name: 'Lưu sơ đồ', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('layout-race')
  await expect(page.getByRole('button', { name: /^B[123], ghế VIP,/ })).toHaveCount(3)
  expect(backend.seats.filter(s => s.rowLabel === 'B').every(s => s.seatType === 'STANDARD')).toBe(true)
})
