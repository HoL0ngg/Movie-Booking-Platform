// Pure seat-editing checks; persistence and authorization are covered by Playwright/API tests.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const vm = require('node:vm')
const ts = require('typescript')
const source = fs.readFileSync(path.join(__dirname, '../src/features/admin/seatLayout.ts'), 'utf8')
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText
const result = { exports: {} }
vm.runInNewContext(compiled, { module: result, exports: result.exports })
const { changeSeatType } = result.exports
const row = [1, 2, 3].map(seatNumber => ({ id: `seat-${seatNumber}`, auditoriumId: 'room', rowLabel: 'A', seatNumber, seatType: 'STANDARD', isActive: true }))
const pair = changeSeatType(row, ['seat-1', 'seat-2'], 'COUPLE')
assert.equal(pair[0].pairedSeatId, 'seat-2')
assert.equal(pair[1].pairedSeatId, 'seat-1')
assert.equal(pair[2].seatType, 'STANDARD')
assert.throws(() => changeSeatType(row, ['seat-1'], 'COUPLE'))
assert.throws(() => changeSeatType(row, ['seat-1', 'seat-3'], 'COUPLE'))
assert.throws(() => changeSeatType(row, ['seat-1', 'seat-2', 'seat-3'], 'COUPLE'))
assert.throws(() => changeSeatType([row[0], { ...row[1], rowLabel: 'B' }], ['seat-1', 'seat-2'], 'COUPLE'))
assert.throws(() => changeSeatType([row[0], { ...row[1], isActive: false }], ['seat-1', 'seat-2'], 'COUPLE'))
assert.throws(() => changeSeatType(pair, ['seat-1'], 'VIP'))
assert.throws(() => changeSeatType(row, [], 'VIP'))
const vip = changeSeatType(pair, ['seat-1', 'seat-2'], 'VIP')
assert.ok(vip.slice(0, 2).every(seat => seat.seatType === 'VIP' && !seat.pairedSeatId))
assert.ok(row.every(seat => seat.seatType === 'STANDARD'), 'Input data remains unchanged')
console.log('Seat pairing, batch edits and selection checks passed')
